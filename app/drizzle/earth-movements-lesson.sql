Pământul nu stă niciodată pe loc. Are două mișcări principale, care se desfășoară în același timp: **rotația** — în jurul propriei axe — și **revoluția** — în jurul Soarelui. Din aceste două mișcări decurg fenomene pe care le trăim zilnic: succesiunea zilei și a nopții, ora diferită de la un capăt la altul al planetei, anotimpurile și împărțirea Pământului în zone de căldură. În această lecție le luăm pe rând și vedem ce consecință produce fiecare.

# Mișcarea de rotație

Rotația este mișcarea Pământului **în jurul axei sale proprii** (linia imaginară care unește cei doi poli).

- **Sensul**: de la vest spre est (spre răsărit). Privit de deasupra polului Nord, Pământul se rotește în sens invers acelor de ceasornic. Tocmai pentru că planeta se învârte spre est, nouă ni se pare că Soarele „răsare” la est și „apune” la vest.
- **Durata**: o rotație completă se face în circa 24 de ore (ziua solară). Față de stele, rotația durează puțin mai puțin — 23 h 56 min 4 s (ziua siderală).
- **Viteza**: viteza unghiulară este aceeași peste tot (15° pe oră, pentru că 360° ÷ 24 h = 15°). În schimb, viteza liniară scade de la Ecuator spre poli: la Ecuator un punct parcurge circa 1670 km/h, iar chiar la poli viteza este zero (polul doar se rotește pe loc). Motivul este simplu: un punct de la Ecuator descrie într-o zi un cerc mult mai mare decât un punct de lângă pol, dar are la dispoziție același timp.

## Consecințele mișcării de rotație

1. **Succesiunea zilei și a nopții.** În orice moment, Soarele luminează doar jumătate din planetă; pe măsură ce Pământul se rotește, fiecare loc trece pe rând prin partea luminată (zi) și prin cea întunecată (noapte).
2. **Mișcarea aparentă a Soarelui și a bolții cerești** de la est la vest. Nu Soarele se mișcă pe cer, ci noi ne mișcăm odată cu Pământul.
3. **Turtirea Pământului la poli.** Rotația generează o forță centrifugă, maximă la Ecuator, care bombează planeta în zona ecuatorială și o turtește la poli.
4. **Forța (efectul) Coriolis** — devierea corpurilor aflate în mișcare.
5. **Necesitatea măsurării timpului pe fuse orare** — pentru că, în același moment, este zi într-o parte a planetei și noapte în alta.

# Forța lui Coriolis

Pentru că Pământul se rotește, orice corp care se deplasează liber pe suprafața lui pare că este **abătut de la drumul drept**:

- în **emisfera nordică**, corpurile în mișcare sunt deviate spre **dreapta**;
- în **emisfera sudică**, spre **stânga**.

Efectul este nul la Ecuator și crește spre poli. Deși nu simțim această forță în viața de zi cu zi, ea se vede clar la fenomene care se desfășoară pe distanțe mari și timp îndelungat:

- **vânturile** planetare (de exemplu alizeele) sunt abătute față de direcția pe care ar avea-o dacă Pământul nu s-ar roti;
- **curenții oceanici** se rotesc în mari bucle, în sensuri opuse în cele două emisfere;
- **râurile mari** își erodează mai puternic malul drept în emisfera nordică.

# Măsurarea timpului și fusele orare

Pentru că Pământul se rotește, ora nu poate fi aceeași peste tot: când la noi este amiază, în partea opusă a planetei este miezul nopții. Ca să existe o ordine, suprafața Pământului a fost împărțită în **24 de fuse orare**, câte unul pentru fiecare oră a zilei.

- Un fus orar acoperă **15° de longitudine** (360° ÷ 24 = 15°). În interiorul unui fus se folosește aceeași oră oficială.
- **Timpul universal** este ora **meridianului de 0°** (meridianul de origine, care trece prin Greenwich). Față de el se socotesc orele celorlalte fuse.
- Deplasându-ne **spre est** (în sensul rotației), **adăugăm** câte o oră pentru fiecare fus traversat; **spre vest**, **scădem** câte o oră.
- **Linia de schimbare a datei** este trasată aproximativ pe meridianul de **180°** (antemeridianul). Când o traversăm **spre est**, rămânem în aceeași zi (repetăm o zi); când o traversăm **spre vest**, trecem direct în ziua următoare.

# Mișcarea de revoluție

Revoluția este mișcarea Pământului **în jurul Soarelui**, pe o traiectorie (orbită) de formă **eliptică**, tot în sensul vest–est.

- **Durata**: un an, mai exact 365 de zile, 6 ore și câteva minute. Cele aproximativ 6 ore care „prisosesc” în fiecare an se adună și, o dată la 4 ani, formează o zi în plus — de aceea există **anul bisect** (cu 366 de zile, ziua suplimentară fiind 29 februarie).
- **Viteza**: circa 29,8 km/s — Pământul parcurge un drum uriaș în jurul Soarelui.
- Fiindcă orbita este eliptică, distanța Pământ–Soare variază puțin: planeta este cel mai aproape de Soare în ianuarie (periheliu) și cel mai departe în iulie (afeliu). **Atenție**: nu distanța dă anotimpurile (altfel toată planeta ar avea vară în același timp).
- **Cauza consecințelor** revoluției este faptul că **axa Pământului rămâne înclinată constant** (circa 66°33′ față de planul orbitei) în tot timpul deplasării. Din această înclinare menținută constant decurg momentele astronomice, anotimpurile și zonele de căldură.

# Momentele astronomice

De-a lungul unei revoluții există patru momente de reper, valabile pentru emisfera nordică:

- **Echinocțiul de primăvară** — 21 martie;
- **Solstițiul de vară** — 22 iunie;
- **Echinocțiul de toamnă** — 23 septembrie;
- **Solstițiul de iarnă** — 22 decembrie.

La **echinocții** („zi egală cu noaptea”), Soarele se află la zenit (exact deasupra capului, la amiază) pe **Ecuator**, iar ziua este egală cu noaptea (12 h cu 12 h) pe toată planeta. La **solstiții**, Soarele ajunge la zenit pe unul dintre tropice: pe **Tropicul Racului** (23°27′ lat. N) la solstițiul de vară și pe **Tropicul Capricornului** (23°27′ lat. S) la solstițiul de iarnă. În emisfera sudică, anotimpurile sunt inversate: 22 iunie înseamnă acolo solstițiul de iarnă.

# Iluminarea Pământului la echinocții și solstiții

Cercul care desparte partea luminată de cea întunecată se numește **cerc de iluminare**. Poziția lui se schimbă în timpul anului, în funcție de felul în care axa înclinată este orientată față de Soare:

- **La echinocții**, cercul de iluminare trece exact prin cei doi poli. Cele două emisfere sunt luminate în mod egal, iar ziua este egală cu noaptea peste tot.
- **La solstițiul de vară (pentru emisfera nordică)**, emisfera nordică este înclinată spre Soare: ea primește razele sub un unghi mai mare, are zile lungi și temperaturi ridicate. Dincolo de **Cercul polar de Nord** este **zi polară** (Soarele nu apune), iar dincolo de Cercul polar de Sud este noapte polară.
- **La solstițiul de iarnă (pentru emisfera nordică)**, situația se inversează: emisfera nordică este orientată dinspre Soare, are zile scurte și nopți lungi, iar la nord de Cercul polar de Nord se instalează **noaptea polară**.

# Înălțimea Soarelui pe cer

**Înălțimea Soarelui** este unghiul sub care razele solare cad pe suprafața Pământului la amiază. Ea depinde de **latitudine** și de **anotimp**:

- cu cât Soarele este mai **sus** pe cer, cu atât razele cad mai aproape de perpendiculară și încălzesc mai puternic, pentru că energia se concentrează pe o suprafață mică;
- cu cât Soarele este mai **jos**, razele cad oblic, se împrăștie pe o suprafață mai mare și încălzesc mai slab.

De aceea la Ecuator, unde razele cad aproape perpendicular tot anul, este cald mereu, iar spre poli, unde razele sunt mereu oblice, este frig. Tot de aceea vara (când Soarele urcă sus pe cer) este mai cald decât iarna (când Soarele rămâne jos), deși vorbim de același loc.

# Consecințele mișcării de revoluție

1. **Succesiunea anotimpurilor.**
2. **Inegalitatea dintre durata zilei și a nopții** de-a lungul anului (cu excepția Ecuatorului, unde ziua este mereu egală cu noaptea).
3. **Variația înălțimii Soarelui pe cer** de la un anotimp la altul.
4. **Împărțirea Pământului în zone de căldură.**

# Anotimpurile

Anotimpurile **nu** apar pentru că Pământul s-ar apropia sau s-ar depărta de Soare, ci pentru că **axa înclinată rămâne orientată la fel** în timpul revoluției. Ca urmare, pe parcursul anului fiecare emisferă este când înclinată spre Soare (primește raze mai directe și mai multă lumină — este vară), când înclinată dinspre Soare (raze oblice, zile scurte — este iarnă).

Din acest motiv, **anotimpurile sunt inversate** între cele două emisfere: când în emisfera nordică este vară, în cea sudică este iarnă. Momentele astronomice (echinocțiile și solstițiile) marchează începutul celor patru anotimpuri: primăvară, vară, toamnă și iarnă.

# Zonele de căldură

În funcție de unghiul sub care primesc razele Soarelui, pe Pământ se disting cinci **zone de căldură (zone termice)**, delimitate de tropice și de cercurile polare:

- **Zona caldă (tropicală)** — între cele două tropice (23°27′ lat. N și S). Cuprinde Ecuatorul; aici Soarele ajunge la zenit de două ori pe an, razele cad aproape perpendicular și temperaturile sunt ridicate tot timpul anului.
- **Două zone temperate** — între tropice și cercurile polare (66°33′ lat. N și S). Razele cad oblic, iar cele patru anotimpuri sunt bine distincte. În aceste zone se află și România.
- **Două zone reci (polare)** — între cercurile polare și poli. Razele cad foarte oblic, apar ziua și noaptea polară, iar temperaturile sunt scăzute tot anul.

