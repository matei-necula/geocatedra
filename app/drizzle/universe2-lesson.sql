Sistemul Solar este alcătuit din Soare și din toate corpurile cosmice care se rotesc în jurul lui: planete, sateliți, planete pitice, asteroizi, meteoriți și comete. Toate sunt ținute împreună de gravitația Soarelui.

# Soarele

- Este o stea de mărime medie, situată într-unul dintre brațele Căii Lactee (brațul Orion), la o distanță de circa 150 milioane km de Pământ (1 unitate astronomică).
- Totalizează aproximativ 99% din masa Sistemului Solar și este alcătuit mai ales din hidrogen (circa 71%) și heliu (circa 28%).
- Are o mișcare de rotație neuniformă: circa 25 de zile la ecuator și 35 de zile în zonele polare.

Structura internă a Soarelui, de la centru spre exterior:

- Nucleu — circa 15 milioane °K; aici au loc reacțiile termonucleare (fuziunea care transformă hidrogenul în heliu și eliberează energie).
- Învelișul radiativ — energia se transmite prin radiație (de la circa 7 la circa 2 milioane °K).
- Învelișul convectiv — energia urcă prin mișcări de convecție (de la circa 2 milioane la circa 5700 °K).
- Fotosfera — suprafața vizibilă, circa 5500–6000 °K; aici apar petele solare (mai reci, circa 4500 °K).
- Cromosfera — circa 4000–20 000 °K; aici apar protuberanțele solare.
- Coroana solară — circa 1–3 milioane °K; de aici pornește vântul solar (fluxuri de plasmă).

Activitatea Soarelui crește și scade cu o periodicitate de circa 11 ani (ciclul al 25-lea, 2019–2030, cu un maxim în 2024). Coroana solară devine vizibilă în timpul eclipselor totale de Soare; ultima eclipsă totală vizibilă din România a avut loc pe 11 august 1999.

# Formarea Sistemului Solar

Sistemul Solar s-a format dintr-o nebuloasă care s-a concentrat treptat sub efectul gravitației: nebuloasă → protostea (viitorul Soare) → disc protoplanetar (un disc de gaz și praf care se rotește în jurul protostelei) → planetoizi → planete, sateliți, asteroizi și comete.

# Planetele

Planetele se împart în două grupe, după alcătuire și mărime:

- Planetele telurice (interioare): Mercur, Venus, Terra și Marte — mici, solide, dense, alcătuite din roci.
- Giganții gazoși (exterioare): Jupiter, Saturn, Uranus și Neptun — foarte mari, fără suprafață solidă, cu atmosfere groase și sisteme de inele.

# Asteroizii (planetoizii)

- Se află într-o centură, între planetele interioare și cele exterioare.
- Sunt considerați „blocuri de construcție” rămase din formarea planetelor.
- Au formă neregulată și sunt alcătuiți din rocă și/sau metal.
- Cel mai mare corp din centură este planeta pitică Ceres.

# Meteoriții

- Sunt alcătuiți din fier și rocă, rezultați mai ales din coliziunile dintre asteroizi.
- Se desprind din centura de asteroizi, atrași de gravitația altor planete sau sateliți; la impactul cu suprafața generează cratere.
- La trecerea prin atmosfera terestră se dezintegrează și produc fenomene luminoase — meteorii, numiți popular „stele căzătoare”.

# Centura Kuiper

- Se află la marginea Sistemului Solar și este alcătuită din corpuri înghețate și planete pitice (de exemplu Pluto, Makemake și Haumea), care orbitează dincolo de Neptun. (Charon nu este o planetă pitică, ci satelitul lui Pluto.)

# Norul lui Oort și cometele

- Norul lui Oort este învelișul cel mai îndepărtat al Sistemului Solar, alcătuit mai ales din comete (gheață de apă, metan, etan, monoxid de carbon) și obiecte stâncoase.
- Cometele sunt corpuri din gheață și praf care orbitează Soarele pe traiectorii foarte alungite (de la eliptice la hiperbolice). Sunt numite popular „stele cu coadă”.
- Structura unei comete: nucleu solid, comă (învelișul gazos din jurul nucleului) și coadă de gaz și praf. Coada apare când cometa se apropie de Soare și o parte din materie se volatilizează; de aceea coada este mereu orientată dinspre Soare.

# Planetele, pe scurt

- Mercur — fără atmosferă, plin de cratere; temperaturi extreme (de la −180 °C la +430 °C); se rotește foarte încet — o rotație în jurul axei durează circa 59 de zile terestre, iar un an mercurian (o revoluție) circa 88 de zile.
- Venus — atmosferă groasă de CO₂ care reține căldura, fiind cea mai fierbinte planetă (circa +465 °C); strălucește puternic („Luceafărul”); se rotește invers față de celelalte planete (sensul E–V).
- Terra — singura planetă cu apă în toate cele trei stări de agregare și cu biosferă variată; atmosferă de azot și oxigen; are un satelit natural, Luna.
- Marte — „planeta roșie”, cu sol bogat în oxizi de fier; are calote glaciare la poli și doi sateliți mici (Phobos și Deimos).
- Jupiter — cea mai mare planetă; atmosferă de hidrogen și heliu, cu Marea Pată Roșie (o furtună uriașă și persistentă); radiază mai multă energie decât primește de la Soare; are mulți sateliți, cei mai mari fiind Io, Europa, Ganimede și Calisto.
- Saturn — celebru pentru inelele numeroase, alcătuite din gheață și rocă; are cea mai mică densitate dintre planete (mai mică decât a apei); cel mai mare satelit este Titan.
- Uranus — are axa de rotație înclinată aproape 98°, astfel încât se rotește „culcat”, aproape pe orbită; atmosferă de hidrogen, heliu și metan.
- Neptun — cea mai îndepărtată planetă; atmosferă cu metan; are Marea Pată Întunecată (o furtună temporară) și satelitul Triton.

# Luna — satelitul Terrei

- Luna are perioada de rotație egală cu perioada de revoluție (27,32 zile), de aceea ne arată mereu aceeași față.
- Geneză: se presupune că o proto-planetă de mărimea lui Marte, numită Theia, a lovit tangențial Pământul la circa 40–50 de milioane de ani după formarea Sistemului Solar; din materialul expulzat s-a format, prin condensare, Luna de azi.
- Fazele Lunii (după partea luminată pe care o vedem de pe Pământ): lună nouă, corn în creștere, primul pătrar, cocoșată în creștere, lună plină, cocoșată în descreștere, al doilea pătrar, corn în descreștere.
- Eclipsele: eclipsa de Soare are loc când Luna se așază între Soare și Pământ și îi acoperă lumina; eclipsa de Lună are loc când Pământul se așază între Soare și Lună, iar Luna intră în umbra Pământului.

