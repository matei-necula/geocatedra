Ca orice corp ceresc, Pământul are o serie de însușiri proprii: o anumită formă și dimensiuni, o axă înclinată, gravitație și magnetism, o căldură internă, o structură pe învelișuri, o densitate și o alcătuire chimică. În această lecție le luăm pe rând și vedem cum se leagă unele de altele.

# Forma și dimensiunile Pământului

Forma Pământului a fost descrisă tot mai exact, printr-o succesiune de aproximări:

- Sfera — o primă aproximare, simplă, dar grosieră.
- Elipsoidul de rotație — corp turtit la poli și bombat la ecuator. Această formă este specifică corpurilor omogene (ca alcătuire) aflate în rotație: rotația produce o forță centrifugă, maximă la ecuator, care bombează planeta în zona ecuatorială.
  - Circumferința la Ecuator = 40 075 km, iar la poli = 40 008 km.
  - Raza ecuatorială = 6378 km, iar raza polară = 6357 km.
- Geoidul — suprafața continuă de la nivelul mediu al oceanelor și mărilor deschise (lipsite de maree și valuri), prelungită imaginar pe sub continente. Este nivelul de 0 m, folosit ca reper pentru altitudini. Abaterea geoidului față de elipsoid este de circa ±120 m.
- Terroidul — forma reală a Pământului. Apare pentru că materia care alcătuiește planeta nu este omogenă din punct de vedere fizic și chimic și nu este distribuită uniform pe verticală sau pe orizontală. Pământul este ușor bombat la polul N și la latitudini medii în emisfera sudică și ușor scobit la polul S.

# Înclinarea axei de rotație

Axa de rotație a Pământului nu este verticală, ci înclinată:

- față de verticală: circa 23°27′;
- față de planul orbitei: circa 66°33′.

Cele două unghiuri sunt complementare (împreună dau 90°) — descriu aceeași înclinare, măsurată din repere diferite. Înclinarea se menține constantă în timpul mișcării de revoluție, iar acest lucru face ca emisferele să primească razele solare sub unghiuri diferite de-a lungul anului. De aici rezultă succesiunea anotimpurilor și inegalitatea dintre durata zilei și a nopții.

# Gravitația

- Gravitația este fenomenul fizic natural prin care corpurile se atrag reciproc, cu o forță a cărei intensitate depinde de masele corpurilor și de distanța dintre ele (forța crește cu masele și scade cu distanța).
- La suprafața Pământului, accelerația gravitațională variază între 9,78 și 9,82 m/s², în funcție de latitudine: scade de la poli spre Ecuator. La Ecuator raza este mai mare și se adaugă efectul forței centrifuge produse de rotație, astfel încât același corp cântărește acolo puțin mai puțin decât la poli.

# Magnetismul

- Pământul se comportă ca un magnet uriaș: are un câmp de forță generat din interior.
- Originea câmpului: forțele de convecție din nucleul extern fluid. Mișcarea materiei metalice topite (bună conducătoare de electricitate) generează câmpul magnetic — un fel de „dinam” natural.
- Axa polilor magnetici face un unghi de circa 11,5° cu axa de rotație a Pământului (= declinație magnetică). De aceea polii magnetici nu coincid cu polii geografici:
  - polul N magnetic: Insula Prințul de Wales, la 76°12′ lat. N și 101° long. V;
  - polul S magnetic: în Antarctica, la circa 67° lat. S și 142° long. E.
- Liniile câmpului magnetic se extind mult în spațiu (cca. 10 raze terestre) și formează magnetosfera.
- Magnetosfera este influențată de activitatea solară: dirijează vântul solar (fluxul de particule încărcate venit de la Soare) spre polii magnetici, unde acesta produce aurore polare (boreale în emisfera nordică, australe în cea sudică). Aurorele se manifestă la altitudini de peste 100 km și pot dura de la câteva minute la câteva ore. Acționând ca un scut, magnetosfera deviază o mare parte din particulele dăunătoare ale vântului solar și protejează astfel planeta.
- Paleomagnetismul studiază schimbările câmpului magnetic în timp (înregistrate în roci), ceea ce arată că poziția polilor și câmpul magnetic nu au rămas neschimbate.

# Căldura internă

Temperatura crește pe măsură ce coborâm spre interiorul Pământului. Două mărimi descriu această creștere:

- Treapta geotermică = adâncimea pe care trebuie să cobori pentru ca temperatura să crească cu 1°C (în litosferă, circa 33 m pentru fiecare 1°C).
- Gradientul geotermic = creșterea de temperatură la fiecare 100 m de adâncime.

Căldura internă provine din două surse:

- Radioactivitatea — circa 90%: dezintegrarea radioactivă a unor izotopi (de exemplu ai uraniului și potasiului) eliberează energie sub formă de căldură. Este sursa principală.
- Căldura reziduală — circa 10%: energia rămasă de la formarea și diferențierea chimică a planetei.

# Structura internă

Pământul este alcătuit din învelișuri concentrice. De la centru spre exterior:

- Nucleul — diametru de circa 7000 km; temperatură între 2800° și 5000°C.
  - Nucleul intern: între 6370 și 5100 km adâncime; alcătuit din nichel și fier (Ni, Fe); solid. Deasupra lui se află discontinuitatea Lehmann. Deși este cel mai fierbinte, rămâne solid din cauza presiunii uriașe din centrul planetei.
  - Nucleul extern: între 5100 și 2900 km adâncime; nichel, fier și crom (Ni, Fe, Cr); fluid. Deasupra lui se află discontinuitatea Gütenberg-Wiechert. Aici iau naștere curenții care generează câmpul magnetic.
- Mantaua — grosime de circa 2900 km; temperatură între 1300° și 1400°C.
  - Mantaua inferioară: între 2900 și 400/700 km adâncime; solidă. Deasupra ei se află discontinuitatea Repetti.
  - Mantaua superioară (astenosfera): între 400/700 și 30/70 km adâncime; fluidă, cu comportament plastic. Deasupra ei se află discontinuitatea Mohorovičić. Pe astenosfera plastică se sprijină și se deplasează plăcile litosferice.
- Scoarța (crusta / litosfera) — mai groasă sub continente (80–100 km) și mult mai subțire sub oceane (10–20 km). De la suprafață spre adâncime cuprinde:
  - pătura sedimentară (la suprafață);
  - pătura granitică (40–80 km grosime), prezentă mai ales sub continente;
  - pătura bazaltică (20–30 km sub continente, 10–20 km sub oceane).

Discontinuitățile (Lehmann, Gütenberg-Wiechert, Repetti, Mohorovičić) sunt suprafețe la care proprietățile materiei — compoziția sau starea fizică — se schimbă brusc; ele despart, de fapt, învelișurile și au fost puse în evidență prin felul în care se propagă undele seismice.

# Densitatea

Densitatea medie a Pământului este de circa 5,52 g/cm³. Rocile de la suprafață au densități mult mai mici (în jur de 2,7 g/cm³), ceea ce arată că interiorul planetei — mai ales nucleul, alcătuit din metale grele — este mult mai dens decât scoarța.

# Alcătuirea chimică

Pe învelișuri, denumirile vin din simbolurile elementelor chimice dominante:

- Litosfera – Sial (siliciu, aluminiu);
- Mantaua superioară – Sima (siliciu, magneziu);
- Mantaua inferioară – Crofesima (crom, fier, magneziu, siliciu);
- Nucleul extern – Nifesima (nichel, fier, siliciu, magneziu);
- Nucleul intern – Nife (nichel, fier).

Se observă că, spre interior, cresc proporțiile elementelor grele (fier, nichel), de aceea densitatea crește spre centrul Pământului.

