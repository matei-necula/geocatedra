**Atmosfera** este învelișul de aer al Pământului (din greacă *athmos* = aer și *spherein* = sferă, înveliș). Este stratul în care se petrec vremea și clima, care ne apără de radiațiile periculoase ale Soarelui și în care respirăm. În această lecție vedem cum este alcătuită atmosfera, cum se așază straturile ei pe verticală, ce factori dau naștere climei și care sunt elementele climatice pe care le măsurăm zi de zi.

# Alcătuirea atmosferei

## Compoziția chimică

Aerul este un amestec de gaze. Principalele sunt:

- **azotul (N₂) – 78,09%**;
- **oxigenul (O₂) – 20,95%**;
- **argonul – 0,93%**;
- **dioxidul de carbon (CO₂) – 0,03%**;
- alte gaze în cantități mici: metan, hidrogen, heliu, neon, xenon și **vapori de apă**.

Fiecare element are un rol esențial pentru viață. Accidental, în atmosferă mai apar praf, polen și diferiți poluanți.

## Forma atmosferei

Atmosfera nu este o pătură cu grosime egală peste tot: este **mai bombată (mai groasă) la Ecuator** și **mai subțire la poli**, din cauza mișcării de rotație a Pământului. **Densitatea** aerului **scade cu altitudinea**, la fel și **temperatura** în stratul de jos. De aceea aproape toate schimbările meteorologice se petrec numai în partea de jos a atmosferei.

# Structura verticală a atmosferei

De la sol în sus, atmosfera este împărțită în mai multe straturi, deosebite prin felul în care se schimbă temperatura cu altitudinea.

## Troposfera

- Se întinde între **0 și 8–12 km** și cuprinde circa **90% din masa atmosferei**.
- Temperatura **scade** cu altitudinea, cu aproximativ **6,4 °C la fiecare 1000 m** (gradient termic vertical), până la circa **−60 °C** la partea superioară.
- Aici se află cea mai mare parte a vaporilor de apă, care formează ceața și norii și dau **precipitațiile**. Practic, **vremea se petrece în troposferă**.

## Stratosfera

- Se întinde între **12 și 50 km**.
- Între **20 și 40 km** se află **stratul de ozon**, care protejează viața de pe Pământ împotriva **radiațiilor ultraviolete (UV)**.
- Temperatura **crește** de la −60 °C până la circa −4 °C la partea superioară.
- La partea de jos se manifestă **curenții-jet (curenți-fulger)**, cu viteze de peste 500 km/h.

## Mezosfera

- Se întinde între **50 și 80 km**.
- Temperatura **scade** de la −4 °C până la circa **−80 °C** — cele mai joase temperaturi din atmosferă.

## Ionosfera (Termosfera)

- Se întinde între **80 și 1000 km**.
- Aici se produc **aurorele polare** — fenomene luminoase colorate din zonele polare, apărute când particulele venite de la Soare se ciocnesc de atomii și moleculele de aici.
- Se mai numește **termosferă**, pentru că temperatura crește foarte mult, până la circa **1600 °C**.
- Are mai multe straturi ionizate (D, E, F) care **reflectă undele radio** emise de pe Pământ și absorb o parte din radiațiile solare.

## Exosfera

- Se întinde la altitudini **mai mari de 1000 km** și face trecerea spre spațiul cosmic.
- Aici se află **centurile de radiații Van Allen**: una interioară (la 3000–4000 km, cu protoni de mare energie) și una exterioară (la 15000–20000 km, cu electroni de mare energie).

# Factorii genetici ai climei

Clima unui loc se naște din trei categorii de factori:

1. **Factorii radiativi** — **radiația solară**, principala sursă de energie. Doar o parte din ea ajunge la suprafață: prin atmosferă, radiația suferă procese de **absorbție** (ozonul reține o parte din UV, iar CO₂ și vaporii de apă rețin o parte din infraroșii), **difuzie** și **reflexie** (circa 30% este reflectată înapoi în spațiu). Diferența dintre radiația primită și cea pierdută se numește **bilanț radiativ**.
2. **Factorii dinamici** — **circulația maselor de aer** (vânturile) care mută căldura și umezeala dintr-o regiune în alta.
3. **Factorii fizico-geografici** — caracteristicile suprafeței terestre: **raportul dintre uscat și apă**, **relieful** (altitudinea, expunerea și orientarea culmilor), **curenții oceanici**, lacurile și fluviile mari, stratul de zăpadă și gheață, **vegetația** și activitățile omenești.

# Circulația generală a atmosferei

Aerul se deplasează pe glob după un model repetabil, format din brâuri de vânturi. De la Ecuator spre poli întâlnim:

- **calmul ecuatorial** — zonă cu vânturi slabe, unde aerul cald urcă;
- **alizeele** — vânturi constante care bat dinspre tropice spre Ecuator;
- **vânturile de vest** — bat în zonele temperate, dinspre vest spre est;
- **vânturile polare** — bat dinspre poli spre latitudinile mai joase.

La înălțime, la limita dintre troposferă și stratosferă, se manifestă **curenții-jet** — curenți de aer foarte rapizi (100–200 km/h): unul **polar** (la 9–12 km) și unul **tropical** (la 10–16 km), în fiecare emisferă.

# Elementele climatice

Cele trei elemente pe care le urmărim pentru a descrie clima sunt **temperatura**, **precipitațiile** și **vânturile**.

## Temperatura

- Temperatura medie anuală pe glob este de aproximativ **13 °C**.
- Ea **scade de la Ecuator spre poli**: 20–30 °C în zona caldă, 10–20 °C în zonele temperate și 0 / −20 °C spre poli.
- Cele mai ridicate medii anuale (peste 28 °C) sunt în Sahara și Arabia; cele mai coborâte (−40 / −50 °C) în Antarctica.
- Recorduri: **maxima 56,7 °C** (Valea Morții, California, SUA); **minima −89,2 °C** (Vostok, Antarctica, 1983).
- Pe hartă, temperatura se reprezintă prin **izoterme** — linii care unesc punctele cu aceeași temperatură. Izotermele au trasee mai uniforme deasupra oceanelor decât deasupra continentelor.

## Inversiunea termică

De regulă, în troposferă temperatura **scade** cu altitudinea. Se întâmplă însă și invers: un strat de aer rece rămâne captiv jos, iar deasupra lui se așază aer mai cald. Acest fenomen se numește **inversiune termică**.

**Cum se produce.** În nopțile senine și liniștite, mai ales iarna, solul pierde repede căldura prin radiație și răcește aerul de deasupra lui. Aerul rece, fiind mai dens și mai greu, se scurge pe versanți și se adună în formele joase de relief — **văi, depresiuni și bazine intramontane**. Așa se ajunge ca în vale să fie mai frig decât pe versantul de deasupra ei.

**Unde se vede cel mai bine.** În depresiunile intramontane, unde aerul rece nu are pe unde să plece. În România, exemplul clasic este **Depresiunea Brașov (Țara Bârsei)**, unde s-au înregistrat unele dintre cele mai scăzute temperaturi din țară.

**Ce urmări are:**

- **ceață persistentă** și nori jos, care se pot menține toată ziua;
- **poluarea rămâne captivă**: stratul de aer cald de deasupra se comportă ca un capac și împiedică aerul poluat să se ridice și să se împrăștie. De aceea, iarna, în orașele din depresiuni aerul devine greu de respirat;
- **inversiunea de vegetație**: fiindcă la fundul depresiunii este mai frig, speciile iubitoare de căldură urcă pe versant, iar molidul și pinul coboară în vale — exact invers față de etajarea obișnuită.

## Precipitațiile

**Precipitațiile** reprezintă totalitatea particulelor de apă, lichide sau solide, provenite din atmosferă. Se formează atunci când aerul se răcește, iar vaporii de apă se condensează sau îngheață, dând naștere norilor din care cad precipitațiile.

După formă, **norii** pot fi: **cirrus** (la 8–10 km, albi și transparenți), **cumulus** (2–8 km, cu aspect pufos), **stratus** (sub 2 km, ca un voal cenușiu), **nimbus** (groși și întunecați) și **cumulonimbus** (dezvoltați mult pe verticală, care dau cele mai multe precipitații).

Precipitațiile pot fi:

- **în cădere liberă**: ploaie, ninsoare, lapoviță, burniță, măzăriche, grindină;
- **formate la suprafață**: rouă, brumă, chiciură, polei;
- după cauză: **convective** (aerul cald urcă și se răcește), **orografice** (aerul urcă peste munți) și **frontale** (aerul cald alunecă peste un aer rece).

Pe hartă, precipitațiile se reprezintă prin **izohiete** — linii care unesc punctele cu aceeași cantitate de precipitații. Cele mai reduse cantități (sub 250 mm/an) sunt în deșerturi și în zonele polare; recordul de uscăciune este în **deșertul Atacama**. Cele mai mari cantități (3000–4000 mm/an) sunt în zonele musonice; recordul mondial este la **Mawsynram, în India** (circa 12000 mm/an).

## Vânturile

Pe lângă vânturile marii circulații, există și vânturi **regionale** și **locale**:

- **Musonii** — vânturi regionale din sudul și estul Asiei: **musonul de vară** bate dinspre Oceanul Indian spre uscat (cald și umed, aduce ploi bogate), iar **musonul de iarnă** bate dinspre uscat spre ocean (uscat).
- **Brizele** — vânturi locale pe litoral, care își schimbă direcția de două ori pe zi: **briza de zi** bate dinspre mare spre uscat, iar **briza de noapte** dinspre uscat spre mare; sau montane, care își schimbă direcția de două ori pe zi: **briza de zi** bate dinspre vale spre culme, iar **briza de noapte** dinspre culme spre vale.
- **Foehnul** — vânt local cald și uscat, care coboară pe versanții adăpostiți ai munților, la începutul primăverii, și grăbește topirea zăpezii.

