Litosfera, învelișul rigid de la exteriorul Pământului, este alcătuită din **roci**. Ca să înțelegem scoarța terestră, trebuie să știm din ce este făcută și cum s-au format materialele ei.



# Minerale și roci



Un **mineral** este o substanță naturală, cu o compoziție chimică bine definită și cu o structură ordonată (deseori sub formă de cristale). Exemple de minerale: cuarțul, feldspatul, mica, calcitul, sarea (halitul).



O **rocă** este un **agregat natural de minerale** — adică o îngrămădire de unul sau mai multe minerale legate între ele. Unele roci sunt formate dintr-un singur mineral (calcarul, din calcit), altele din mai multe (granitul, din cuarț, feldspat și mica).



După **modul în care s-au format (geneză)**, rocile se împart în trei mari categorii: **magmatice**, **sedimentare** și **metamorfice**.



# Categoriile de minerale



Mineralele se grupează după **compoziția lor chimică**. Iată principalele categorii, cu exemplele care se întâlnesc cel mai des:



- **Elemente native** — minerale formate dintr-un **singur element chimic**, nelegat de altul: aurul, argintul, cuprul, sulful, grafitul și diamantul (ambele, carbon pur).

- **Silicați** — cea mai numeroasă categorie: peste 90% din scoarța terestră. Sunt combinații de siliciu și oxigen cu diverse metale: cuarțul, feldspații, mica, olivina, talcul.

- **Oxizi** — combinații ale unui metal cu oxigenul. Multe sunt minereuri de fier sau aluminiu: hematitul, magnetitul, bauxita, corindonul (din care se taie rubinul și safirul).

- **Carbonați** — conțin gruparea carbonat; fac efervescență în contact cu acizii. Calcitul (din care e făcut calcarul și marmura), dolomitul, malachitul.

- **Sulfuri** — combinații ale unui metal cu sulful; au adesea luciu metalic. Pirita („aurul nebunilor"), galena (minereu de plumb), blenda (minereu de zinc), cinabrul (minereu de mercur).

- **Sulfați** — conțin gruparea sulfat. Gipsul (din care se face ipsosul), anhidritul, celestina, baritina.

- **Halogenuri** — combinații cu clor, fluor sau brom. Halitul (sarea gemă, sarea de bucătărie), silvina, fluorina.

- **Fosfați** — conțin gruparea fosfat. Apatitul (materia primă pentru îngrășăminte) și turcoazul.



**De ce contează?** Categoria unui mineral îi explică proprietățile și folosul: silicații dau duritatea rocilor de construcție, oxizii și sulfurile sunt **minereurile** din care se scot metalele, carbonații și sulfații dau materiale de construcție (var, ciment, ipsos), iar halogenurile ne dau sarea. Unele minerale, rare și frumos cristalizate, devin **pietre prețioase** (diamantul, rubinul, safirul, smaraldul) sau **semiprețioase** (ametistul, turcoazul, malachitul, agatul).



# Roci magmatice (eruptive)



Rocile magmatice se formează prin **răcirea și solidificarea magmei** (topitura fierbinte din adâncul Pământului). Modul în care se răcește magma le împarte în două grupe.



## Roci intruzive (plutonice)

Se formează atunci când magma se răcește **lent, în adâncime**, sub scoarță. Fiindcă răcirea este înceată, mineralele au timp să crească, iar roca are **cristale mari**, vizibile cu ochiul liber. Exemple:



- **granit** — cea mai răspândită rocă intruzivă;

- **gabrou**;

- **diorit**;

- **sienit**.



## Roci efuzive (vulcanice)

Se formează când magma ajunge la **suprafață** (sub formă de lavă) și se răcește **repede**. Fiindcă răcirea este rapidă, mineralele nu apucă să crească, iar roca are **cristale mici** sau chiar o masă **sticloasă**. Exemple:



- **bazalt** — cea mai răspândită rocă efuzivă;

- **andezit**;

- **riolit**;

- **obsidian** — sticlă vulcanică, răcită atât de brusc încât nu are cristale;

- **piatra ponce** — plină de goluri lăsate de gazele din lavă, atât de ușoară încât plutește pe apă.



Ideea-cheie: **cu cât răcirea este mai lentă, cu atât cristalele sunt mai mari**.



# Roci sedimentare



Rocile sedimentare se formează la **suprafața** scoarței, prin mai multe etape: **dezagregarea și eroziunea** altor roci, **transportul** materialului (de ape, vânt, gheață), **depunerea (sedimentarea)** lui și, în final, **consolidarea**. Fiindcă materialul se depune în etape, rocile sedimentare sunt dispuse în **strate (straturi)** suprapuse — o trăsătură care le face ușor de recunoscut. Tot în ele se păstrează **fosilele**.



După proveniența materialului, se deosebesc trei tipuri:



- **detritice (clastice)** — din fragmente (detritus) provenite din alte roci: pietriș, nisip, argilă. Prin consolidare dau **gresie** (din nisip), **conglomerat** (din pietriș) sau argile;

- **de precipitare chimică** — din substanțe dizolvate în apă, care se depun când apa se evaporă sau se saturează: **sare gemă**, **gips**, **calcar** (o parte dintre calcare);

- **organogene (biogene)** — din resturile unor viețuitoare (plante sau animale): **cărbunii** și **petrolul** (din resturi de plante și organisme), **calcarul cochilifer** și **creta** (din cochilii și schelete de animale marine).



# Roci metamorfice



Rocile metamorfice se formează prin **transformarea (metamorfismul)** unor roci deja existente, sub acțiunea **temperaturii și a presiunii mari** din adâncul scoarței. Foarte important: transformarea are loc **în stare solidă** — roca nu se topește, dar mineralele ei se rearanjează, iar roca își schimbă aspectul și proprietățile.



Fiecare rocă metamorfică provine dintr-o rocă anume:



- **gnais** — din granit;

- **marmură** — din calcar;

- **cuarțit** — din gresie;

- **ardezie (șisturi)** — din argilă.



# Circuitul rocilor



Rocile nu sunt veșnice: ele se transformă mereu unele în altele, într-un **circuit** neîncetat.



- o rocă magmatică sau metamorfică, ajunsă la suprafață, este **dezagregată și erodată**, iar fragmentele ei dau naștere unei roci **sedimentare**;

- o rocă sedimentară, îngropată sub presiune și temperatură mare, se transformă într-o rocă **metamorfică**;

- dacă temperatura crește și mai mult, orice rocă se poate **topi**, redevenind **magmă**, care apoi se răcește și formează din nou o rocă magmatică.



Astfel, aceleași materiale trec, în timp geologic, dintr-o categorie în alta. Tocmai de aceea calcarul poate fi și rocă sedimentară (chimică sau organogenă), iar prin metamorfism devine marmură.



# Utilitatea rocilor



Rocile sunt o resursă de bază pentru oameni:



- **materiale de construcție** — granitul, bazaltul, marmura, calcarul, gresia, nisipul și argila (pentru cărămizi și ciment);

- **combustibili** — cărbunii și petrolul, roci organogene care ne dau energie;

- **materii prime și resurse** — sarea gemă (în alimentație și industrie), gipsul, minereurile din care se extrag metale.



A cunoaște tipurile de roci înseamnă a înțelege atât relieful din jurul nostru, cât și bogățiile pe care ni le oferă scoarța terestră.

