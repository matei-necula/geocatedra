## Forma atmosferei

Atmosfera nu este o pătură cu grosime egală peste tot: este **mai bombată (mai groasă) la Ecuator** și **mai subțire la poli**, din cauza mișcării de rotație a Pământului. **Densitatea** aerului **scade cu altitudinea**, la fel și **temperatura** în stratul de jos. De aceea aproape toate schimbările meteorologice se petrec numai în partea de jos a atmosferei.

# Structura verticală a atmosferei

De la sol în sus, atmosfera este împărțită în mai multe straturi, deosebite prin felul în care se schimbă temperatura cu altitudinea.

