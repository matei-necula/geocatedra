**Precipitațiile** reprezintă totalitatea particulelor de apă, lichide sau solide, provenite din atmosferă. Se formează atunci când aerul se răcește, iar vaporii de apă se condensează sau îngheață, dând naștere norilor din care cad precipitațiile.

