# Circulația generală a atmosferei

Aerul se deplasează pe glob după un model repetabil, format din brâuri de vânturi. De la Ecuator spre poli întâlnim:

- **calmul ecuatorial** — zonă cu vânturi slabe, unde aerul cald urcă;
