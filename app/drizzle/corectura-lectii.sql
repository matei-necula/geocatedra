# Tipurile de contacte dintre plăci

La marginile lor, plăcile intră în contact în trei feluri:

- **Contacte divergente** — plăcile se **depărtează** una de alta. Între ele urcă magmă care se solidifică și creează scoarță nouă. Aici apar **zonele de rift** și **dorsalele** (lanțuri muntoase submarine). Exemple: **riftul est-african**, **riftul Mării Roșii** și **dorsala medio-atlantică**.
- **Contacte convergente** — plăcile se **apropie și se ciocnesc**:
  - dacă o placă oceanică întâlnește una continentală, cea oceanică (mai densă) alunecă pe dedesubt — proces numit **subducție** — și se formează o **fosă oceanică** adâncă, însoțită de vulcani și cutremure (de exemplu **Cercul de Foc al Pacificului**, cu cele mai adânci fose, precum Fosa Marianelor);
  - dacă se ciocnesc două plăci continentale, marginile lor se încrețesc și se ridică **munți** înalți (de exemplu Himalaya).
- **Contacte transformante** — plăcile **alunecă lateral**, una pe lângă cealaltă, fără a crea sau distruge scoarță; aici se produc cutremure puternice.

# Vulcanismul de tip „hot-spot”

Nu toți vulcanii apar la marginile plăcilor. În unele locuri, un „punct fierbinte” (**hot-spot**) din manta străpunge placa chiar prin mijlocul ei. Pe măsură ce placa se deplasează deasupra punctului fix, se formează un **șir de vulcani și insule**, cel mai vechi la un capăt și cel mai nou deasupra punctului fierbinte. Exemplul clasic este **arhipelagul Hawaii**.

# Procesele asociate dinamicii plăcilor

Mișcarea plăcilor declanșează mai multe categorii de procese:

1. **Cutremurele (seismele).** Locul din adânc unde se produce ruptura se numește **hipocentru (focar)**, iar punctul de la suprafață, situat deasupra lui, se numește **epicentru**. Un cutremur se măsoară în două feluri: **scara Richter** măsoară **magnitudinea** (cantitatea de energie eliberată), iar **scara Mercalli** măsoară **intensitatea** (efectele resimțite la suprafață). Cel mai puternic seism înregistrat a fost în **Chile, la 22 mai 1960 (9,5 grade Richter)**.
2. **Vulcanismul.** Aparatul vulcanic cuprinde: **vatra** (rezervorul de magmă din adânc), **coșul** (canalul de urcare), **conul** și **craterul**. La erupție sunt expulzate lavă, bombe, lapili și cenușă, precum și gaze și vapori de apă.
3. **Mișcările orogenetice** — cele care formează munții (orogeneze); principalele au fost cea **caledonică**, cea **hercinică** și cea **alpină** (cea mai recentă, care a format Alpii, Carpații, Himalaya).
4. **Mișcările epirogenetice** — ridicări și coborâri lente, pe suprafețe întinse. Cele **pozitive** (de ridicare a uscatului) sunt însoțite de **regresiuni** marine (marea se retrage); cele **negative** (de coborâre) sunt însoțite de **transgresiuni** marine (marea înaintează). Ele sunt provocate de încărcarea sau ușurarea scoarței — de exemplu instalarea sau topirea calotelor de gheață, ori acumularea de sedimente și erodarea munților.
5. **Magmatismul** — răcirea și consolidarea magmei **în interiorul scoarței**, cu formarea unor corpuri magmatice (de exemplu batolite).

