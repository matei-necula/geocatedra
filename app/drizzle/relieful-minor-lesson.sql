Fiecare tabel are patru coloane: **tipul de relief**, **agenții** morfogenetici, **procesele** geomorfologice și **formele** de relief rezultate. Citind un rând pe orizontală, urmărești cum un anumit agent, prin anumite procese, dă naștere unor forme precise.

