## De reținut

- **Relieful minor** este sculptat de **agenții externi**, peste relieful major creat de forțele interne.
- Fiecare agent lucrează prin lanțul **agent → procese → forme**: dezagregare, eroziune, transport, acumulare (și dizolvare, la calcar).
- **Apa** (râuri, ploi), **gheața**, **vântul**, **valurile mării**, **gravitația**, **viețuitoarele** și **omul** sunt principalii agenți.
- **Roca și structura** sunt **factori pasivi**: nu creează relief, dar hotărăsc ce forme apar.
- Aceleași procese, dar agenți sau roci diferite, dau forme diferite — de aici marea varietate a reliefului minor.');
