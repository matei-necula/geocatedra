Relieful major al Terrei — continentele și bazinele oceanice, munții, podișurile și câmpiile — este creat de **forțele interne (tectonice)**. Peste el, **agenții externi** lucrează neîncetat și îl remodelează, sculptând **relieful minor**: forme mai mici, dar extrem de variate. Fiecare agent extern (apa, gheața, vântul, valurile, gravitația, viețuitoarele, omul) acționează printr-un set de **procese** (dezagregare, eroziune, transport, acumulare, dizolvare) și lasă **forme** caracteristice. Lecția urmărește, în tabele, lanțul:

**agent → procese → forme.**

Roca și structura geologică nu creează relief prin ele însele, dar hotărăsc ce forme apar — de aceea le numim **factori pasivi**.

