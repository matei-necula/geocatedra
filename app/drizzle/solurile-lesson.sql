**Solul** este stratul afânat de la suprafața uscatului, în care se întrepătrund materia minerală, materia organică, apa, aerul și viețuitoarele, și care are însușirea de bază numită **fertilitate** — capacitatea de a hrăni plantele. Învelișul de sol al planetei alcătuiește **pedosfera**, un adevărat **ecosistem** în care roca, apa, aerul și viața interacționează. Solul este puntea dintre roca moartă și viața de pe uscat.

## Cum se formează solul

Solul se formează foarte încet (sute și mii de ani) sub acțiunea unor **factori pedogenetici**:

- **clima** (temperatura și precipitațiile) — factorul cel mai important, care hotărăște ce procese au loc;
- **roca-mamă (materialul parental)** — din care provine partea minerală;
- **vegetația** — dă materia organică;
- **microorganismele și viețuitoarele mici** (bacteriile, râmele) — descompun resturile și amestecă solul;
- **apa** — dizolvă și transportă substanțele;
- **relieful** — hotărăște cât se scurge sau se adună apa;
- **timpul** — solurile mature se formează în mii de ani;
- **omul** — prin agricultură poate îmbunătăți sau distruge solul.

Fiindcă cel mai important factor este clima, **tipurile mari de sol de pe glob urmează, în general, zonele climatice și de vegetație.**

## Orizonturile solului

Privit dintr-o groapă (un profil de sol), solul apare alcătuit din straturi suprapuse numite **orizonturi**, notate cu litere, de sus în jos:

- **O (litiera)** — stratul de la suprafață, din frunze, iarbă și crengi în diferite stadii de descompunere; de culoare închisă;
- **A** — orizontul **bioacumulativ**, unde materia organică descompusă (**humusul**) se amestecă cu partea minerală; este solul vegetal, cel mai bogat și mai activ biologic, de culoare închisă;
- **E (eluvial)** — orizontul de **spălare (eluviere)**: apa care coboară cară de aici mineralele solubile și o parte din materia organică; rămâne sărăcit, de culoare deschisă;
- **B (iluvial)** — orizontul de **acumulare (iluviere)**: aici se depun argila, humusul și oxizii spălați din orizonturile de deasupra; are culori variate, de la roșu și galben la maro și gri;
- **C** — **materialul parental**, roca-mamă slab consolidată, puțin atinsă de procesele de formare a solului;
- **R** — **roca parentală** compactă (nealterată), la baza profilului.

Pe lângă acestea pot apărea orizonturi speciale, precum cel **gleic (G)** — format acolo unde apa băltește și nu mai există oxigen — sau cel **turbos**, din resturi vegetale slab descompuse, în locuri reci și umede.

## Procese pedogenetice

În funcție de climă, în sol se desfășoară procese diferite, care duc la tipuri diferite de sol. Trei sunt esențiale:

- **podzolirea** — proces caracteristic climatelor **umede și răcoroase**: apa spală din orizontul superior argila, materia organică și compușii de fier și aluminiu și îi depune mai jos; rezultă un orizont eluvial deschis la culoare și un orizont B de acumulare. Așa se formează **spodosolurile** (sub pădurile de conifere) și **alfisolurile / argiluvisolurile** (sub pădurile de foioase);
- **calcifierea** — proces al climatelor **secetoase (stepe și deșerturi)**, unde evaporația e mare, apa nu spală în adânc, iar **carbonatul de calciu se acumulează** în sol; formează **molisolurile** (soluri de stepă, foarte fertile — cernoziomurile) și **aridisolurile / calcisolurile** (soluri de deșert);
- **lateritizarea** — proces al climatelor **calde și umede (ecuatoriale, tropicale)**: apa multă și căldura îndepărtează bazele și silicea și lasă pe loc oxizii și hidroxizii de fier și aluminiu, care dau solului o culoare roșiatică. Formează **oxisolurile / feralsolurile** (sub pădurea ecuatorială) și **ultisolurile** (sub savană).

Se vede limpede legătura: **fiecărei zone climatice și de vegetație îi corespunde un proces pedogenetic și un tip de sol.**

## Proprietățile solului

Solurile se deosebesc între ele prin însușiri pe care le putem observa și măsura:

- **fertilitatea** — capacitatea de a hrăni plantele (cea mai importantă);
- **culoarea** — indică bogăția în humus (închisă = mult humus) sau prezența oxizilor de fier (roșiatică);
- **textura** — dată de mărimea particulelor: **nisip** (2–0,02 mm), **praf** (0,02–0,002 mm) și **argilă** (sub 0,002 mm); un sol poate fi nisipos, lutos sau argilos;
- **structura** — felul în care particulele se leagă în agregate;
- **porozitatea și permeabilitatea** — cât aer și apă încap în sol și cât de ușor le lasă să treacă;
- **pH-ul (reacția chimică)** — dacă solul este acid, neutru sau bazic.

Aceste proprietăți hotărăsc cât de potrivit este un sol pentru agricultură — de aceea studiul solului nu este doar teorie, ci stă la baza hranei oamenilor.

