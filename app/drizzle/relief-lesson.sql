**Relieful** este totalitatea formelor (denivelărilor) suprafeței terestre — de la munți și câmpii până la fundul oceanelor. Suprafața Pământului se împarte în două mari domenii: **domeniul continental** (uscatul) și **domeniul oceanic** (acoperit de ape). În această lecție vedem cum sunt repartizate uscatul și apa, care sunt treptele majore de relief și cum se formează ele.

# Repartiția uscatului și a apei

Apa acoperă cea mai mare parte a planetei:

- **oceanele și mările — circa 71%** din suprafață, cu o adâncime medie de aproximativ **3794 m**;
- **uscatul — circa 29%**, cu o altitudine medie de aproximativ **875 m**.

**Domeniul continental** are circa **149 milioane km² (59%)**, dar este repartizat inegal: mult mai mult în **emisfera nordică (40%)** decât în cea sudică (19%). De aceea emisfera nordică mai este numită și „emisfera continentelor".

**Domeniul oceanic** are circa **361 milioane km² (41%)** și cuprinde patru oceane:

- **Pacific** — cel mai întins și cel mai adânc; aici se află **Fosa Marianelor (circa −11 022 m)**, cel mai adânc punct de pe Terra;
- **Atlantic** — al doilea ca mărime (Fosa Puerto Rico, circa −9219 m);
- **Indian** (Fosa Java, circa −7455 m);
- **Arctic** — cel mai mic și mai puțin adânc.

# Altitudini și adâncimi extreme

- Cel mai înalt punct de pe uscat: **vârful Everest (circa 8850 m)**, la granița Nepal–Tibet.
- Cel mai jos punct de pe uscat: țărmul **Mării Moarte (circa −411 m)**.
- Cel mai adânc punct al planetei: **Fosa Marianelor (circa −11 022 m)**.

Fiecare continent are propriile extreme: **Africa** — vf. Kilimanjaro (5895 m); **Europa** — vf. Elbrus (5642 m); **Asia** — Everest; **America de Nord** — vf. Denali/McKinley (6194 m); **America de Sud** — vf. Aconcagua (6960 m); **Australia** — vf. Kosciuszko (2228 m); **Antarctica** — Masivul Vinson (4897 m).

# Treptele majore de relief

După altitudine și înfățișare, uscatul se împarte în patru trepte:

- **Munții** — peste 800–1000 m; vârfuri ascuțite, versanți abrupți (pante mari, peste 20°), văi adânci (peste 400–500 m), alcătuiți din roci dure (șisturi cristaline, roci magmatice).
- **Dealurile** — între circa 200 și 1000 m; vârfuri rotunjite. Predomină suprafețele înclinate; roci mai moi (nisipuri, pietrișuri, argile) în straturi înclinate.
- **Podișurile** — peste circa 300 m (până la 1000 m); au **culmi largi și netede** și versanți abrupți; roci moi așezate mai ales în straturi orizontale.
- **Câmpiile** — sub circa 300 m; suprafețe netede, văi puțin adânci (sub 100 m); roci moi în straturi orizontale.

Atenție la deosebirea **deal – podiș**: ambele pot avea altitudini asemănătoare, dar la **deal** predomină suprafețele înclinate, iar la **podiș** predomină suprafețele largi și netede de pe culmi.

# Elementele morfologice ale reliefului

Pentru a descrie exact o formă de relief se folosesc câteva mărimi:

- **altitudinea (sau adâncimea) absolută** — înălțimea față de nivelul mării;
- **adâncimea fragmentării** — cât de adânc au tăiat văile în relief (diferența de nivel dintre culme și vale);
- **densitatea fragmentării** — cât de des se succed văile și culmile pe o suprafață;
- **panta** — înclinarea versanților.

# Geneza treptelor de relief

Fiecare treaptă se formează într-un mod caracteristic:

- **Munții** — prin **încrețirea (cutarea) scoarței = orogeneză** și prin erupții vulcanice;
- **Dealurile** — prin cutarea scoarței sau prin acumularea materialelor aduse de râuri la poalele munților;
- **Podișurile** — prin depunerea materialelor transportate de râuri sau prin **tocirea (eroziunea) munților**;
- **Câmpiile** — prin **acumularea** materialelor aduse de fluvii.

# Formarea munților prin orogeneză (teoria geosinclinalului)

Munții de încrețire se formează într-un proces lung, în două mari etape:

**A. Etapa de geosinclinal** — o zonă a scoarței coboară continuu, iar în ea se acumulează sedimente groase de sute și mii de metri. Sub greutatea și căldura din adânc, o parte din sedimente devin plastice și se cutează. Această etapă poate dura **100–150 milioane de ani** (Carpații s-au format în circa 150 de milioane de ani).

**B. Etapa de orogen** — sensul mișcării se schimbă, din coborâre în **ridicare**, iar zona este comprimată. Ea are **trei faze**:

1. **Faza inversiunilor** — fundul geosinclinalului începe să se ridice; prin răcirea magmelor granitice și a rocilor metamorfice (șisturi cristaline), fundul se consolidează.
2. **Faza de închidere a geosinclinalului** — spre marginea dinspre uscat apare o zonă de lăsare, o depresiune marginală numită **avanfosă**, în care se acumulează sedimentele erodate din munte; astfel iau naștere **dealurile prealpine (subcarpatice)**.
3. **Faza ridicărilor în bloc** — se formează adevăratul **lanț muntos**, însoțit de forme de relief marginale: dealuri premontane, **podișuri interioare** (ex. Podișul Transilvaniei) sau exterioare (ex. Podișul Moldovei), câmpii și **podișuri piemontane** (ex. Piemontul Getic) și **câmpii de acumulare** (ex. Câmpia Română, Câmpia de Vest).

# Nivelarea reliefului: peneplena și pediplena

Odată formați, munții nu rămân neschimbați: agenții externi (apa, vântul, ghețarii, temperatura) îi **tocesc** necontenit. După milioane de ani, un lanț muntos poate fi redus la o suprafață aproape plană, numită **suprafață de nivelare**:

- **peneplena** — suprafața de nivelare rezultată în climatele temperate și umede;
- **pediplena** — suprafața de nivelare rezultată în climatele calde și aride (semideșertice).

Existența acestor suprafețe arată că relieful este rezultatul unei „lupte" permanente între **forțele interne** (care înalță relieful — orogeneza, vulcanismul) și **forțele externe** (care îl netezesc — eroziunea).');
