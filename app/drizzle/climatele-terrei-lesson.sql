**Clima** este regimul mediu, pe mulți ani, al vremii dintr-un loc (temperaturi, precipitații, vânturi). Ea nu este la fel peste tot pe glob, iar felul în care se schimbă de la Ecuator spre poli ne ajută să înțelegem repartiția vegetației, a apelor și a solurilor.

## De ce clima nu este la fel peste tot

Clima depinde de mai mulți **factori climatogeni**:

- **latitudinea (unghiul razelor solare)** — la Ecuator razele cad aproape drept și încălzesc puternic; spre poli cad oblic și încălzesc slab. De aici marea împărțire pe **zone de căldură**;
- **circulația maselor de aer și vânturile permanente** (alizeele, vânturile de vest, vânturile polare, musonii), care aduc aer cald sau rece, umed sau uscat;
- **repartiția uscatului și a apei** — apa se încălzește și se răcește greu, uscatul repede; de aici deosebirea dintre climatele **oceanice** (blânde, umede) și cele **continentale** (cu ierni și veri extreme, mai uscate);
- **curenții oceanici**, care încălzesc sau răcesc țărmurile;
- **relieful și altitudinea** — cu cât urcăm, cu atât temperatura scade.

Combinând acești factori, Pământul se împarte în trei mari **zone climatice**: caldă, temperată și rece. În fiecare, mai multe **tipuri de climă** susțin o anumită **zonă biogeografică** (tip de vegetație). Pentru fiecare tip reținem: latitudinea, temperatura medie anuală (**TMA**), precipitațiile medii anuale (**PMA**), vânturile și vegetația.

## Zona caldă (climatele calde)

Se întinde de o parte și de alta a Ecuatorului, unde razele solare cad aproape vertical tot anul. Cuprinde:

- **climatul ecuatorial** (0–5° N și S): TMA 24–28 °C, PMA foarte mari (1.000–3.000 mm/an), aer calm și umed, **un singur anotimp** cald-ploios; vegetație de **pădure ecuatorială** deasă;
- **climatul subecuatorial** (5–12°): TMA ~28 °C, PMA 500–1.500 mm, cu **două anotimpuri** — unul ploios și unul secetos —, aduse de alizee; vegetație de **savană**;
- **climatul tropical-arid** (12–30°): TMA 25–30 °C, PMA foarte mici (100–250 mm), sub bătaia uscată a alizeelor; aici se află marile **deșerturi calde** (Sahara);
- **climatul tropical-musonic** (12–30°): TMA 20–25 °C, cu **musoni** care aduc, vara, ploi uriașe (până la 12.000 mm/an) și, iarna, secetă; vegetație de **pădure musonică**.

## Zona temperată (climatele temperate)

Se află între tropice și cercurile polare, acolo unde bat mai ales **vânturile de vest** și se resimt cel mai clar **cele patru anotimpuri**. Este cea mai variată zonă:

- **subtropical-mediteranean** (30–40°): TMA 15–17 °C, veri calde și uscate, ierni blânde și ploioase; **păduri și tufișuri** mereu verzi;
- **subtropical cu ploi de vară** (25–35°): TMA 17–25 °C, PMA 750–1.500 mm, sub musoni și alizee; **păduri**;
- **temperat-oceanic** (40–60°): TMA 10–15 °C, ploi bogate tot anul (1.000–2.000 mm), veri răcoroase și ierni blânde datorită oceanului; **păduri de foioase**;
- **temperat-continental-umed** (40–60°): TMA 5–10 °C, PMA mai mici (500–750 mm), cu ierni geroase și veri calde; vegetație de **stepă și silvostepă**;
- **temperat-rece (boreal)** (50–60°): TMA în jur de 0 °C, ierni lungi și aspre; **păduri de conifere (taiga)**;
- **temperat-continental-arid** (40–50°): TMA 5–8 °C, PMA sub 250 mm; **deșerturi temperate** (Gobi).

## Zona rece (climatele reci)

Se întinde spre poli, dincolo de cercurile polare, unde razele solare cad foarte oblic și energia primită este mică. Bat **vânturile polare**, reci și uscate. Cuprinde:

- **climatul subpolar** (60–66°): TMA sub 10 °C, PMA 100–300 mm; vegetație scundă de **tundră** (mușchi, licheni, arbuști pitici);
- **climatul polar** (66–90°): TMA sub 0 °C tot anul, foarte puține precipitații (100–200 mm); un **deșert rece**, acoperit de calote de gheață, aproape lipsit de vegetație.

## De reținut

- **Clima** depinde de latitudine, de vânturi, de repartiția uscat-apă, de curenții oceanici și de relief; factorul principal este **latitudinea**, care hotărăște câtă căldură primește un loc.
- Pământul se împarte în trei **zone climatice** — caldă, temperată și rece —, fiecare cu mai multe tipuri de climă și cu vegetația proprie.
- Există o **simetrie**: de la Ecuator spre poli, temperatura scade treptat, iar tipurile de climă și vegetația se schimbă în fâșii paralele, la fel în emisfera nordică și în cea sudică.');
