// Ingest documente (PDF / PowerPoint / Word) ca materiale de tip „fisier”:
// materiale + traduceri + material_assets + upload R2.
// Idempotent: șterge întâi materialul cu același (grade, topic, slug).
// Usage: node scripts/ingest-docs.mjs <manifest.json> --target local|remote
//
// Fiecare intrare din manifest:
//   { gradeId, topicSlug, library?, slug, position?, status?, title, description?,
//     files: ["cale/catre/fisier.pdf", "cale/catre/fisier.pptx"] }
// Ordinea din `files` devine `idx` — primul fișier e cel afișat primul în pagină.
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { readFileSync, statSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const ti = args.indexOf("--target");
const target = ti >= 0 ? args[ti + 1] : "local";
const manifestPath = args.find((a, i) => a !== "--target" && i !== ti + 1);
if (!manifestPath || !["local", "remote"].includes(target)) {
	console.error("Usage: node scripts/ingest-docs.mjs <manifest.json> --target local|remote");
	process.exit(1);
}

// Ține pasul cu ALLOWED_DOCS din app/lib/assets.ts.
const MIME = {
	pdf: "application/pdf",
	doc: "application/msword",
	docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
	ppt: "application/vnd.ms-powerpoint",
	pptx: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
};
const MAX_BYTES = 25 * 1024 * 1024; // la fel ca MAX_ASSET_BYTES
const roleForMime = (mime) => (mime === "application/pdf" ? "pdf" : "file");

const esc = (s) => String(s).replace(/'/g, "''");

// `shell: true` (necesar pe Windows pentru `npx`) nu pune ghilimele pe argumente,
// iar căile materialelor au spații — le cităm noi.
const shell = process.platform === "win32";
const q = (a) => (shell && /[\s&()]/.test(a) ? `"${a}"` : a);

function putObject(key, path, mime) {
	const argv = ["wrangler", "r2", "object", "put", `catedra-media/${key}`, "--file", path, "--content-type", mime, `--${target}`];
	execFileSync("npx", argv.map(q), { stdio: ["ignore", "ignore", "inherit"], shell });
}
const now = Date.now();
const items = JSON.parse(readFileSync(manifestPath, "utf8"));
if (!Array.isArray(items)) {
	console.error("Manifestul trebuie să fie un array de materiale.");
	process.exit(1);
}

const lines = ["-- generated by scripts/ingest-docs.mjs"];

for (const m of items) {
	if (!m.gradeId || !m.topicSlug || !m.slug || !m.title) {
		throw new Error(`Intrare fără gradeId/topicSlug/slug/title: ${JSON.stringify(m)}`);
	}
	const id = randomUUID();
	const where = `grade_id='${esc(m.gradeId)}' AND topic_slug='${esc(m.topicSlug)}' AND slug='${esc(m.slug)}'`;
	lines.push(
		`DELETE FROM material_translations WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM material_assets WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM materials WHERE ${where};`,
		`INSERT INTO materials (id, grade_id, topic_slug, type, library, slug, position, status, is_teaser, created_at, updated_at) VALUES ('${id}','${esc(m.gradeId)}','${esc(m.topicSlug)}','fisier','${esc(m.library || "teacher")}','${esc(m.slug)}',${Number(m.position) || 0},'${esc(m.status || "published")}',0,${now},${now});`,
		`INSERT INTO material_translations (material_id, locale, title, description, body) VALUES ('${id}','ro','${esc(m.title)}','${esc(m.description || "")}','');`,
	);
	(m.files || []).forEach((path, idx) => {
		const bytes = statSync(path).size;
		if (bytes > MAX_BYTES) throw new Error(`Prea mare (${bytes} B, max ${MAX_BYTES}): ${path}`);
		const ext = path.split(".").pop().toLowerCase();
		const mime = MIME[ext];
		if (!mime) throw new Error(`Extensie nesuportată: ${path}`);
		const assetId = randomUUID();
		const key = `materials/${id}/${assetId}`;
		lines.push(
			`INSERT INTO material_assets (id, material_id, role, idx, r2_key, mime, bytes, created_at) VALUES ('${assetId}','${id}','${roleForMime(mime)}',${idx},'${key}','${mime}',${bytes},${now});`,
		);
		putObject(key, path, mime);
	});
	console.log(`OK ${m.slug} (${(m.files || []).length} fișiere, ${target})`);
}

writeFileSync("drizzle/ingest-docs.sql", lines.join("\n") + "\n", "utf8");
console.log(`\nAplică SQL-ul cu:\n  npx wrangler d1 execute catedra --${target} --file ./drizzle/ingest-docs.sql`);
