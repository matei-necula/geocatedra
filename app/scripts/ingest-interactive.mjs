// Ingest aplicații interactive: un fișier HTML de sine stătător devine un
// material de tip `interactiv`, cu HTML-ul păstrat chiar în corpul materialului
// (sunt zeci de KB, nu au nevoie de R2). Randarea se face în iframe izolat —
// vezi components/InteractiveApp.tsx.
// Idempotent: șterge întâi materialul cu același (grade, topic, slug).
// Usage: node scripts/ingest-interactive.mjs <manifest.json>
//
// Fiecare intrare: { gradeId, topicSlug, slug, position?, status?, title,
//                    description?, file: "cale/catre/app.html" }
import { randomUUID } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const manifestPath = process.argv[2];
if (!manifestPath) {
	console.error("Usage: node scripts/ingest-interactive.mjs <manifest.json>");
	process.exit(1);
}

// Căile către fișiere sunt relative la manifest, nu la directorul din care rulezi.
const baza = dirname(resolve(manifestPath));
const esc = (s) => String(s).replace(/'/g, "''");
const now = Date.now();
const items = JSON.parse(readFileSync(manifestPath, "utf8"));
if (!Array.isArray(items)) {
	console.error("Manifestul trebuie să fie un array de materiale.");
	process.exit(1);
}

const lines = ["-- generated by scripts/ingest-interactive.mjs"];
for (const m of items) {
	if (!m.gradeId || !m.topicSlug || !m.slug || !m.title || !m.file) {
		throw new Error(`Intrare fără gradeId/topicSlug/slug/title/file: ${JSON.stringify(m)}`);
	}
	const html = readFileSync(resolve(baza, m.file), "utf8");
	// Plasa de siguranță: un fișier care cheamă resurse din afară n-ar merge
	// oricum în sandbox și ar trimite elevii pe alte site-uri.
	const extern = html.match(/(?:src|href)\s*=\s*["']https?:\/\/[^"']+/gi);
	if (extern) throw new Error(`${m.slug}: fișierul cheamă resurse externe:\n  ${extern.slice(0, 5).join("\n  ")}`);

	const id = randomUUID();
	const where = `grade_id='${esc(m.gradeId)}' AND topic_slug='${esc(m.topicSlug)}' AND slug='${esc(m.slug)}'`;
	lines.push(
		`DELETE FROM material_translations WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM material_assets WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM materials WHERE ${where};`,
		`INSERT INTO materials (id, grade_id, topic_slug, type, library, slug, position, status, is_teaser, created_at, updated_at) VALUES ('${id}','${esc(m.gradeId)}','${esc(m.topicSlug)}','interactiv','${esc(m.library || "student")}','${esc(m.slug)}',${Number(m.position) || 0},'${esc(m.status || "published")}',0,${now},${now});`,
		`INSERT INTO material_translations (material_id, locale, title, description, body) VALUES ('${id}','ro','${esc(m.title)}','${esc(m.description || "")}','${esc(html)}');`,
	);
	console.log(`OK ${m.slug} (${Math.round(html.length / 1024)} KB)`);
}

writeFileSync("drizzle/ingest-interactive.sql", lines.join("\n") + "\n", "utf8");
console.log(`\nAplică SQL-ul cu:\n  npx wrangler d1 execute catedra --remote --file ./drizzle/ingest-interactive.sql`);
