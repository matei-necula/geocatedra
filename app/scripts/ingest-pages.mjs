// Ingest materiale răsfoibile: fiecare material e un teanc de pagini-imagine
// (tip `prezentare`, body {"kind":"pagini","count":N}, assets cu idx 0..N-1).
// Idempotent: șterge întâi materialul cu același (grade, topic, slug).
// Usage: node scripts/ingest-pages.mjs <manifest.json> --target local|remote
//
// Fiecare intrare: { gradeId, topicSlug, library?, slug, position?, status?,
//                    title, description?, pages: ["cale/Slide1.webp", ...] }
// Ordinea din `pages` e ordinea de răsfoire.
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { readFileSync, statSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const ti = args.indexOf("--target");
const target = ti >= 0 ? args[ti + 1] : "local";
const manifestPath = args.find((a, i) => a !== "--target" && i !== ti + 1);
if (!manifestPath || !["local", "remote"].includes(target)) {
	console.error("Usage: node scripts/ingest-pages.mjs <manifest.json> --target local|remote");
	process.exit(1);
}

const MIME = { webp: "image/webp", png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg" };
const MAX_BYTES = 25 * 1024 * 1024;
const esc = (s) => String(s).replace(/'/g, "''");

// `shell: true` (necesar pe Windows pentru `npx`) nu citează argumentele.
const shell = process.platform === "win32";
const q = (a) => (shell && /[\s&()]/.test(a) ? `"${a}"` : a);
function putObject(key, path, mime) {
	const argv = ["wrangler", "r2", "object", "put", `catedra-media/${key}`, "--file", path, "--content-type", mime, `--${target}`];
	execFileSync("npx", argv.map(q), { stdio: ["ignore", "ignore", "inherit"], shell });
}

const now = Date.now();
const items = JSON.parse(readFileSync(manifestPath, "utf8"));
if (!Array.isArray(items)) {
	console.error("Manifestul trebuie să fie un array de materiale.");
	process.exit(1);
}

const lines = ["-- generated by scripts/ingest-pages.mjs"];
let totalPagini = 0;

for (const m of items) {
	if (!m.gradeId || !m.topicSlug || !m.slug || !m.title) {
		throw new Error(`Intrare fără gradeId/topicSlug/slug/title: ${JSON.stringify(m)}`);
	}
	const pages = m.pages || [];
	if (pages.length === 0) throw new Error(`Materialul ${m.slug} n-are nicio pagină.`);

	const id = randomUUID();
	const where = `grade_id='${esc(m.gradeId)}' AND topic_slug='${esc(m.topicSlug)}' AND slug='${esc(m.slug)}'`;
	const body = JSON.stringify({ kind: "pagini", count: pages.length });
	lines.push(
		`DELETE FROM material_translations WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM material_assets WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM materials WHERE ${where};`,
		`INSERT INTO materials (id, grade_id, topic_slug, type, library, slug, position, status, is_teaser, created_at, updated_at) VALUES ('${id}','${esc(m.gradeId)}','${esc(m.topicSlug)}','prezentare','${esc(m.library || "teacher")}','${esc(m.slug)}',${Number(m.position) || 0},'${esc(m.status || "published")}',0,${now},${now});`,
		`INSERT INTO material_translations (material_id, locale, title, description, body) VALUES ('${id}','ro','${esc(m.title)}','${esc(m.description || "")}','${esc(body)}');`,
	);

	pages.forEach((path, idx) => {
		const bytes = statSync(path).size;
		if (bytes > MAX_BYTES) throw new Error(`Prea mare (${bytes} B): ${path}`);
		const ext = path.split(".").pop().toLowerCase();
		const mime = MIME[ext];
		if (!mime) throw new Error(`Extensie nesuportată: ${path}`);
		const assetId = randomUUID();
		const key = `materials/${id}/${assetId}`;
		lines.push(
			`INSERT INTO material_assets (id, material_id, role, idx, r2_key, mime, bytes, created_at) VALUES ('${assetId}','${id}','image',${idx},'${key}','${mime}',${bytes},${now});`,
		);
		putObject(key, path, mime);
	});

	totalPagini += pages.length;
	console.log(`OK ${m.slug} (${pages.length} pagini, ${target})`);
}

writeFileSync("drizzle/ingest-pages.sql", lines.join("\n") + "\n", "utf8");
console.log(`\n${items.length} materiale, ${totalPagini} pagini. Aplică SQL-ul cu:\n  npx wrangler d1 execute catedra --${target} --file ./drizzle/ingest-pages.sql`);
