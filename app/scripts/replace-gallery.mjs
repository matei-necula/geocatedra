// Înlocuiește pozele unei galerii `foto` existente cu un set nou, în ordinea dată.
// Usage: node scripts/replace-gallery.mjs <manifest.json> --target local|remote [--backup <dir>] [--dry]
//
// Manifest: [{ gradeId, topicSlug, slug, images: [{ file, caption }] }]
//   `slug` identifică materialul existent (tip `foto`). Pozele vechi sunt
//   descărcate în `--backup` (dacă e dat), apoi șterse din R2 și din DB;
//   cele noi sunt urcate cu idx 0..N-1 și `captions` din manifest.
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { readFileSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const flag = (name) => {
	const i = args.indexOf(name);
	return i >= 0 ? args[i + 1] : undefined;
};
const target = flag("--target") || "local";
const backupDir = flag("--backup");
const dry = args.includes("--dry");
const manifestPath = args.find((a) => a.endsWith(".json"));
if (!manifestPath || !["local", "remote"].includes(target)) {
	console.error("Usage: node scripts/replace-gallery.mjs <manifest.json> --target local|remote [--backup <dir>] [--dry]");
	process.exit(1);
}

const MIME = { webp: "image/webp", png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg" };
const MAX_BYTES = 25 * 1024 * 1024;
const esc = (s) => String(s).replace(/'/g, "''");
const shell = process.platform === "win32";
const q = (a) => (shell && /[\s&()]/.test(a) ? `"${a}"` : a);
const wrangler = (argv, opts = {}) => execFileSync("npx", ["wrangler", ...argv].map(q), { shell, encoding: "utf8", ...opts });

function d1(sql) {
	const out = wrangler(["d1", "execute", "catedra", `--${target}`, "--json", "--command", sql], { stdio: ["ignore", "pipe", "ignore"] });
	const m = out.match(/^\[/m);
	if (!m) throw new Error(`Răspuns D1 neașteptat:\n${out}`);
	return JSON.parse(out.slice(m.index))[0].results;
}
const r2put = (key, path, mime) =>
	wrangler(["r2", "object", "put", `catedra-media/${key}`, "--file", path, "--content-type", mime, `--${target}`], { stdio: ["ignore", "ignore", "inherit"] });
const r2get = (key, path) =>
	wrangler(["r2", "object", "get", `catedra-media/${key}`, "--file", path, `--${target}`], { stdio: ["ignore", "ignore", "inherit"] });
const r2del = (key) =>
	wrangler(["r2", "object", "delete", `catedra-media/${key}`, `--${target}`], { stdio: ["ignore", "ignore", "inherit"] });

const now = Date.now();
const items = JSON.parse(readFileSync(manifestPath, "utf8"));
const lines = ["-- generated by scripts/replace-gallery.mjs"];
const oldKeys = [];

for (const m of items) {
	const where = `grade_id='${esc(m.gradeId)}' AND topic_slug='${esc(m.topicSlug)}' AND slug='${esc(m.slug)}'`;
	const rows = d1(`SELECT id, type FROM materials WHERE ${where}`);
	if (rows.length !== 1) throw new Error(`Aștept exact un material pentru ${m.slug}, am găsit ${rows.length}.`);
	const { id, type } = rows[0];
	if (type !== "foto") throw new Error(`Materialul ${m.slug} e de tip '${type}', nu 'foto'.`);

	const existing = d1(`SELECT r2_key FROM material_assets WHERE material_id='${id}' ORDER BY idx`);
	console.log(`${m.slug}: ${existing.length} poze vechi -> ${m.images.length} poze noi`);
	if (backupDir && !dry) {
		const dir = join(backupDir, m.slug);
		mkdirSync(dir, { recursive: true });
		existing.forEach((a, i) => r2get(a.r2_key, join(dir, `${String(i).padStart(2, "0")}-${a.r2_key.split("/").pop()}`)));
	}
	oldKeys.push(...existing.map((a) => a.r2_key));

	lines.push(`DELETE FROM material_assets WHERE material_id='${id}';`);
	m.images.forEach((img, idx) => {
		const bytes = statSync(img.file).size;
		if (bytes > MAX_BYTES) throw new Error(`Prea mare (${bytes} B): ${img.file}`);
		const mime = MIME[img.file.split(".").pop().toLowerCase()];
		if (!mime) throw new Error(`Extensie nesuportată: ${img.file}`);
		const assetId = randomUUID();
		const key = `materials/${id}/${assetId}`;
		lines.push(
			`INSERT INTO material_assets (id, material_id, role, idx, r2_key, mime, bytes, created_at) VALUES ('${assetId}','${id}','image',${idx},'${key}','${mime}',${bytes},${now});`,
		);
		if (!dry) r2put(key, img.file, mime);
	});

	const body = JSON.stringify({ captions: m.images.map((i) => i.caption || "") });
	lines.push(
		`UPDATE material_translations SET body='${esc(body)}' WHERE material_id='${id}' AND locale='ro';`,
		`UPDATE materials SET updated_at=${now} WHERE id='${id}';`,
	);
}

mkdirSync("drizzle", { recursive: true });
writeFileSync("drizzle/replace-gallery.sql", lines.join("\n") + "\n", "utf8");
console.log(`\nSQL în drizzle/replace-gallery.sql`);
if (dry) {
	console.log("--dry: n-am urcat și n-am șters nimic.");
	process.exit(0);
}
wrangler(["d1", "execute", "catedra", `--${target}`, "--file", "./drizzle/replace-gallery.sql", "-y"], { stdio: ["ignore", "ignore", "inherit"] });
console.log("SQL aplicat.");
for (const key of oldKeys) r2del(key);
console.log(`${oldKeys.length} obiecte R2 vechi șterse.`);
