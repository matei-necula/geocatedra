// Ingest jocuri: materiale + traduceri + material_assets + upload R2.
// Idempotent: șterge întâi materialul cu același (grade, topic, slug).
// Usage: node scripts/ingest-games.mjs <folder...> --target local|remote
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const ti = args.indexOf("--target");
const target = ti >= 0 ? args[ti + 1] : "local";
const folders = args.filter((a, i) => a !== "--target" && i !== ti + 1);
if (!folders.length || !["local", "remote"].includes(target)) {
	console.error("Usage: node scripts/ingest-games.mjs <folder...> --target local|remote");
	process.exit(1);
}

const MIME = { png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", webp: "image/webp" };
const esc = (s) => String(s).replace(/'/g, "''");
const now = Date.now();
const lines = ["-- generated by scripts/ingest-games.mjs"];

for (const folder of folders) {
	const g = JSON.parse(readFileSync(join(folder, "game.json"), "utf8"));
	const id = randomUUID();
	const where = `grade_id='${esc(g.gradeId)}' AND topic_slug='${esc(g.topicSlug)}' AND slug='${esc(g.slug)}'`;
	lines.push(
		`DELETE FROM material_translations WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM material_assets WHERE material_id IN (SELECT id FROM materials WHERE ${where});`,
		`DELETE FROM materials WHERE ${where};`,
		`INSERT INTO materials (id, grade_id, topic_slug, type, library, slug, position, status, is_teaser, created_at, updated_at) VALUES ('${id}','${esc(g.gradeId)}','${esc(g.topicSlug)}','joc','student','${esc(g.slug)}',${Number(g.position) || 0},'${esc(g.status || "published")}',0,${now},${now});`,
		`INSERT INTO material_translations (material_id, locale, title, description, body) VALUES ('${id}','ro','${esc(g.title)}','${esc(g.description || "")}','${esc(JSON.stringify(g.body))}');`,
	);
	(g.assets || []).forEach((file, idx) => {
		const path = join(folder, file);
		const bytes = statSync(path).size;
		const ext = file.split(".").pop().toLowerCase();
		const mime = MIME[ext];
		if (!mime) throw new Error(`Extensie nesuportată: ${file}`);
		const assetId = randomUUID();
		const key = `materials/${id}/${assetId}`;
		lines.push(
			`INSERT INTO material_assets (id, material_id, role, idx, r2_key, mime, bytes, created_at) VALUES ('${assetId}','${id}','image',${idx},'${key}','${mime}',${bytes},${now});`,
		);
		execFileSync(
			"npx",
			["wrangler", "r2", "object", "put", `catedra-media/${key}`, "--file", path, "--content-type", mime, `--${target}`],
			{ stdio: "inherit", shell: process.platform === "win32" },
		);
	});
	console.log(`OK ${g.slug} (${(g.assets || []).length} assets, ${target})`);
}

writeFileSync("drizzle/ingest-games.sql", lines.join("\n") + "\n", "utf8");
console.log(`\nAplică SQL-ul cu:\n  npx wrangler d1 execute catedra --${target} --file ./drizzle/ingest-games.sql`);
