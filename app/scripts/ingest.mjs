// Bulk-ingest materials from a JSON file (the "ingest-material" skill, CLI form).
// The admin UI is the everyday path; this is for bulk/programmatic import.
//
// Usage:
//   node scripts/ingest.mjs <materials.json>
//   npx wrangler d1 execute catedra --local --file ./drizzle/ingest.sql
//
// Each item: { gradeId, topicSlug, type, library?, title, description?, body,
//              status?, isTeaser?, position? }
//   - `body` may be a string (for "scris") or an object (for joc/examen/foto/
//     prezentare) which is JSON-stringified automatically.
import { randomUUID } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const RO = { ă: "a", â: "a", î: "i", ș: "s", ş: "s", ț: "t", ţ: "t", Ă: "a", Â: "a", Î: "i", Ș: "s", Ş: "s", Ț: "t", Ţ: "t" };
const slugify = (s) =>
	s.replace(/[ăâîșşțţĂÂÎȘŞȚŢ]/g, (c) => RO[c] ?? c)
		.normalize("NFD").replace(/[̀-ͯ]/g, "")
		.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "material";

const file = process.argv[2];
if (!file) {
	console.error("Usage: node scripts/ingest.mjs <materials.json>");
	process.exit(1);
}

const items = JSON.parse(readFileSync(file, "utf8"));
if (!Array.isArray(items)) {
	console.error("Expected a JSON array of materials.");
	process.exit(1);
}

const now = Date.now();
const esc = (s) => String(s).replace(/'/g, "''");
const lines = ["-- generated by scripts/ingest.mjs (append-only)"];

for (const m of items) {
	if (!m.gradeId || !m.topicSlug || !m.type || !m.title) {
		console.error("Skipping item missing gradeId/topicSlug/type/title:", JSON.stringify(m));
		continue;
	}
	const id = randomUUID();
	const slug = slugify(m.slug || m.title);
	const body = typeof m.body === "string" ? m.body : JSON.stringify(m.body ?? "");
	lines.push(
		`INSERT INTO materials (id, grade_id, topic_slug, type, library, slug, position, status, is_teaser, created_at, updated_at) VALUES ('${id}','${esc(m.gradeId)}','${esc(m.topicSlug)}','${esc(m.type)}','${esc(m.library || "student")}','${esc(slug)}',${Number(m.position) || 0},'${esc(m.status || "published")}',${m.isTeaser ? 1 : 0},${now},${now});`,
	);
	lines.push(
		`INSERT INTO material_translations (material_id, locale, title, description, body) VALUES ('${id}','ro','${esc(m.title)}','${esc(m.description || "")}','${esc(body)}');`,
	);
}

mkdirSync("drizzle", { recursive: true });
writeFileSync("drizzle/ingest.sql", lines.join("\n") + "\n", "utf8");
console.log(`Wrote drizzle/ingest.sql. Apply with:\n  npx wrangler d1 execute catedra --local --file ./drizzle/ingest.sql`);
