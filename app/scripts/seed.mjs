const lines = [];
lines.push("-- generated by scripts/seed.mjs");
lines.push("DELETE FROM material_translations;");
lines.push("DELETE FROM materials;");
lines.push("DELETE FROM access_tokens;");

for (const m of materials) {
	const id = randomUUID();
	lines.push(
		`INSERT INTO materials (id, grade_id, topic_slug, type, library, slug, position, status, is_teaser, created_at, updated_at) VALUES ('${id}','${m.grade}','${m.topic}','${m.type}','student','${m.slug}',${m.pos},'published',0,${now},${now});`,
	);
	lines.push(
		`INSERT INTO material_translations (material_id, locale, title, description, body) VALUES ('${id}','ro','${esc(m.title)}','${esc(m.desc)}','${esc(m.body)}');`,
	);
}

// Fixed demo token for instant testing of the student flow.
const demoPlain = "GEO-9-DEMO";
lines.push(
	`INSERT INTO access_tokens (id, token_hash, label, grade_id, valid_from, valid_until, revoked_at, created_at) VALUES ('${randomUUID()}','${sha256(normalize(demoPlain))}','Clasa a 9-a (demo)','9',${now},${endOfSchoolYear()},NULL,${now});`,
);

mkdirSync("drizzle", { recursive: true });
writeFileSync("drizzle/seed.sql", lines.join("\n") + "\n", "utf8");
console.log(`Wrote drizzle/seed.sql with ${materials.length} materials + demo token ${demoPlain}`);
