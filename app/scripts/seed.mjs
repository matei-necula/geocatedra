const now = Date.now();
const esc = (s) => String(s).replace(/'/g, "''");
const sha256 = (s) => createHash("sha256").update(s).digest("hex");
const normalize = (s) => s.trim().toUpperCase().replace(/\s+/g, "");

// end of Romanian school year (15 June), this year or next
function endOfSchoolYear(d = new Date()) {
	const y = d.getUTCFullYear();
	const june = Date.UTC(y, 5, 15, 23, 59, 59);
	return d.getTime() <= june ? june : Date.UTC(y + 1, 5, 15, 23, 59, 59);
}

